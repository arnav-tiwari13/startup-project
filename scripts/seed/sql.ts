// Renders the sample data as one SQL script, for pasting into the Supabase SQL editor (no API key needed there).
// The script only deletes and reloads rows belonging to the two sample restaurant ids, inside one transaction.
import type { SeedRows } from "./generate.ts";
import { SAMPLE_SPECS } from "./specs.ts";

const lit = (v: string | number | boolean): string =>
  typeof v === "number" ? (Number.isFinite(v) ? String(v) : "null") : typeof v === "boolean" ? String(v) : `'${v.replace(/'/g, "''")}'`;

const CHUNK = 400;

function insert(table: string, columns: string[], rows: Record<string, string | number | boolean>[]): string {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += CHUNK) {
    const values = rows.slice(i, i + CHUNK).map((r) => `(${columns.map((c) => lit(r[c])).join(", ")})`);
    out.push(`insert into public.${table} (${columns.join(", ")}) values\n${values.join(",\n")};`);
  }
  return out.join("\n\n");
}

export function toSql(rows: SeedRows, asOf: string): string {
  const ids = SAMPLE_SPECS.map((s) => lit(s.id)).join(", ");
  const clear = ["sales_items", "inventory_counts", "labor_entries", "invoice_items", "invoices", "recipe_items", "menu_items", "ingredients", "vendors"]
    .map((t) => `delete from public.${t} where restaurant_id in (${ids});`)
    .join("\n");

  const parts = [
    `-- platecfo sample data (made up), as of ${asOf}. Generated by scripts/seed-sql.ts.`,
    `-- Paste into the Supabase SQL editor and run. Safe to run again: it replaces only the two sample restaurants' rows.`,
    `-- It never touches any other restaurant.`,
    "begin;",
    clear,
    `insert into public.restaurants (id, name) values\n${rows.restaurants.map((r) => `(${lit(r.id)}, ${lit(r.name)})`).join(",\n")}\non conflict (id) do update set name = excluded.name;`,
    insert("vendors", ["id", "restaurant_id", "name"], rows.vendors),
    insert("ingredients", ["id", "restaurant_id", "name", "unit", "category", "vendor_id"], rows.ingredients),
    insert("menu_items", ["id", "restaurant_id", "name", "price_cents", "active"], rows.menu_items.map((m) => ({ ...m, active: true }))),
    insert("recipe_items", ["restaurant_id", "menu_item_id", "ingredient_id", "qty"], rows.recipe_items),
    insert("invoices", ["id", "restaurant_id", "vendor_id", "invoice_date", "total_cents"], rows.invoices),
    insert("invoice_items", ["restaurant_id", "invoice_id", "ingredient_id", "qty", "unit_cost_cents", "line_total_cents"], rows.invoice_items),
    insert("sales_items", ["restaurant_id", "sale_date", "menu_item_id", "units", "sales_cents"], rows.sales_items),
    insert("inventory_counts", ["restaurant_id", "ingredient_id", "count_date", "qty"], rows.inventory_counts),
    insert("labor_entries", ["restaurant_id", "entry_date", "labor_cents"], rows.labor_entries),
    "commit;",
    `-- Check: expect about ${rows.sales_items.length} sales rows and ${rows.invoices.length} invoices.\nselect (select count(*) from public.sales_items where restaurant_id in (${ids})) as sales_rows,\n       (select count(*) from public.invoices where restaurant_id in (${ids})) as invoices,\n       (select count(*) from public.inventory_counts where restaurant_id in (${ids})) as inventory_counts;`,
  ];
  return `${parts.join("\n\n")}\n`;
}
